#include <stdio.h>

/*
    \n quebra linha 
    \t Tabulação equivalente a tecla TAB
    \" Aspas duplas no printf 
    \' Aspas simples no printf 

*/

int main(){
    printf("\n\nOdair Gabriel\n\n");
    printf("\n\n\tOdair Gabriel\n\n");
    printf("\n\n\t\tOdair Gabriel\n\n");


    printf("\n\n\"Odair Gabriel\"\n");
    printf("\'Odair Gabriel\'");

   
    return 0;
}